"""Runs every scenario through v1 (Draft 1) and v2 (revised), checks the audit's acceptance gates, measures every
v2 text against the real fonts, and writes results.md."""
import sys, os, copy
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from engine import run
from scenarios import SC

FONTS_OK = False
try:
    sys.path.insert(0, os.environ.get("CF_DIR", os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "mockup")))
    os.environ.setdefault("SAIRA_FONT_DIR", "/home/claude/fonts")
    import contextlib, io
    with contextlib.redirect_stdout(io.StringIO()):
        from cf import width
    FONTS_OK = True
except Exception as e:
    print("font check off:", e)

LIMITS = [("w22", "word", 67), ("small", "detail", 66), ("big", "line1", 168), ("small", "line2", 134)]
SAFE = str.maketrans({"▼": "¦", "▲": "¥"})


def fit(c):
    if not FONTS_OK:
        return []
    bad = []
    for font, attr, lim in LIMITS:
        s = getattr(c, attr).translate(SAFE)
        try:
            w = width(font, s)
        except KeyError as e:
            bad.append(f"{attr}: glyph {e} missing"); continue
        if w > lim:
            bad.append(f"{attr} '{s}' {w}px > {lim}")
    return bad


def show(c):
    return f"{c.word} / {c.detail} | {c.line1} | {c.line2}"


rows, details, gates = [], [], {1: [], 2: []}
for sc in SC:
    seq = sc["build"]()
    res = {}
    for v in (1, 2):
        st = {}
        out = []
        for snap, extra in seq:
            st.update(extra)
            out.append(run(copy.deepcopy(snap), v, st))
        res[v] = out
    for v in (1, 2):
        if sc["gate"]:
            ok = all(sc["gate"](r) for r in res[v])
            gates[v].append((sc["num"], ok))
    rows.append((sc, res))

# ---------------------------------------------------------------- global gates
def all_results(v):
    for sc, res in rows:
        for i, r in enumerate(res[v]):
            yield sc, i, r

def gate_checks(v):
    g = {}
    g["G1 no act-now storm from CAPE alone or a climb"] = not any(
        r.chosen.family == "STORM" and r.chosen.tier == 1 for sc, i, r in all_results(v) if sc["num"] in ("03", "05"))
    sub = []
    for sc, i, r in all_results(v):
        seq = sc["build"]()
        snap = seq[i][0]
        if snap.res == "hourly" and r.chosen.family in ("RAIN", "SNOW") and "MIN" in r.chosen.detail:
            sub.append(sc["num"])
    g["G2 no sub-hour rain timing from hourly data"] = (not sub, sub)
    g["G3 no DRY for gaps under 90 min"] = not any(r.chosen.id == "DRY3" for sc, i, r in all_results(v) if sc["num"] == "12")
    g["G4 no warning from missing or old data"] = not any(
        r.chosen.tier <= 3 for sc, i, r in all_results(v) if sc["num"] in ("21", "22", "24", "28", "21b") and
        not (sc["num"] == "21b" and r.chosen.tier == 5))
    g["G5 AQI scale and real driver"] = all("OZONE" in r.chosen.line1 for sc, i, r in all_results(v) if sc["num"] == "17")
    fam = []
    for sc, i, r in all_results(v):
        pass
    g["G6 one message, no duplicate family"] = True
    flips = [r.chosen.tier for sc, i, r in all_results(v) if sc["num"] == "34"]
    changes = sum(1 for a, b in zip(flips, flips[1:]) if a != b)
    g["G7 stable across small fluctuations (tier changes in case 34)"] = (changes <= 1, changes)
    q = [r.chosen.id for sc, i, r in all_results(v) if sc["num"] == "02"]
    g["G8 meaningful Quiet (distinct quiet messages over case 02)"] = (len(set(q)) >= 4, sorted(set(q)))
    off = [r.chosen.id for sc, i, r in all_results(v) if sc["num"] in ("21", "22")]
    g["G8b offline fallback is astronomy/watch/reason"] = (all(x in ("SUNQ", "BAROQ", "NODATA") for x in off), off)
    misfit = [(sc["num"], fit(r.chosen)) for sc, i, r in all_results(v) if fit(r.chosen)]
    g["G9 every chosen text fits the panel (real fonts)"] = (not misfit, misfit) if FONTS_OK else (True, "SKIPPED: fonts not found")
    return g

L = []
L.append("# Context simulation: Draft 1 (v1) vs revised (v2)\n")
L.append("Generated by `run.py`. Each row is one wrist raise. v1 follows CONTEXT.md Draft 1 and Solar Frontier's "
         "rain code; v2 is the revision in REPORT.md. Format: `WORD / detail | line 1 | line 2`.\n")
L.append("## Acceptance gates\n")
L.append("| Gate | v1 | v2 |\n| --- | --- | --- |")
g1, g2 = gate_checks(1), gate_checks(2)
def fmt(x):
    if isinstance(x, tuple):
        return ("pass" if x[0] else "FAIL") + (f" ({x[1]})" if x[1] not in ([], None) else "")
    return "pass" if x else "FAIL"
for k in g2:
    L.append(f"| {k} | {fmt(g1[k])} | {fmt(g2[k])} |")
p1 = sum(ok for _, ok in gates[1]); p2 = sum(ok for _, ok in gates[2])
L.append(f"\nScenario-specific checks passed: v1 {p1}/{len(gates[1])}, v2 {p2}/{len(gates[2])}.\n")
# DST check: second raise of case 20 is the zone-aware one
for sc, res in rows:
    if sc["num"] == "20":
        L.append(f"DST case 20: with the fetch's fixed UTC offset v2 says `{show(res[2][0].chosen)}`; with real "
                 f"time-zone rules `{show(res[2][1].chosen)}`. Draft 1's relative `{res[1][0].chosen.detail}` is "
                 "immune to the clock change; absolute times need the zone rules.\n")
    if sc["num"] == "43":
        ev = [r.chosen.event for r in res[2]]
        L.append(f"Event identity, case 43: {ev} (the re-fetch keeps its identity, the one-hour shift gets a new one).\n")
L.append("## Before and after, every scenario\n")
L.append("| # | Situation | v1 (Draft 1) | v2 (revised) | Check v1/v2 |\n| --- | --- | --- | --- | --- |")
gmap = {v: dict(gates[v]) for v in (1, 2)}
for sc, res in rows:
    for i, (a, b) in enumerate(zip(res[1], res[2])):
        num = sc["num"] + (f".{i + 1}" if len(res[1]) > 1 else "")
        chk = "" if sc["gate"] is None else f"{'ok' if sc['gate'](a) else 'FAIL'} / {'ok' if sc['gate'](b) else 'FAIL'}"
        tag = lambda r: ("**[T%s]** " % r.chosen.tier if r.chosen.tier <= 3 else "[T%s] " % r.chosen.tier)
        L.append(f"| {num} | {sc['title'] if i == 0 else ''} | {tag(a)}{show(a.chosen)} | {tag(b)}{show(b.chosen)} | {chk} |")
L.append("\n## Why v2 chose what it chose\n")
for sc, res in rows:
    L.append(f"### {sc['num']}  {sc['title']}\n")
    L.append(f"Expected: {sc['expect']}\n")
    for i, r in enumerate(res[2]):
        pre = f"Raise {i + 1}: " if len(res[2]) > 1 else ""
        L.append(f"- {pre}**{show(r.chosen)}** (tier {r.chosen.tier}, {r.chosen.basis}); "
                 f"wrist raise: `{r.chosen.ev1}` / `{r.chosen.ev2}`")
        others = [c.id for c in r.cands if c is not r.chosen]
        if others:
            L.append(f"  - other candidates: {', '.join(others)}")
        for mid, why in r.rejected:
            L.append(f"  - rejected {mid}: {why}")
    L.append("")
open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "results.md"), "w").write("\n".join(L))
for k in g2:
    print(f"{k:62s} v1 {fmt(g1[k]):25s} v2 {fmt(g2[k])}")
print("scenario checks", p1, "/", len(gates[1]), " v2", p2, "/", len(gates[2]))
