"""Context Ahead: regenerates the generated parts of the project.

  resources/fonts/word.*, tiny.*, icons.*   the Signal word font, the tiny label font and the icon font
  source/Ic.mc                              icon glyph numbers and sizes
  source/SetText.mc                         the on-watch settings menu texts
  resources/settings/*.xml                  phone settings (Garmin Connect app): properties, list, strings
  resources/drawables/launcher_icon.png     the 40 x 40 launcher icon

The time, small, big, mid and med fonts are Solar Frontier's (same design, renamed "Context Ahead Pixel"),
copied as they are. Needs Saira Semi Condensed (ExtraBold, SemiBold) in SAIRA_FONT_DIR (Google Fonts, SIL OFL).

    SAIRA_FONT_DIR=/path/to/saira python3 tools/make_project.py
"""
import os, sys, json
from xml.sax.saxutils import escape
from PIL import Image, ImageDraw

TOOLS = os.path.dirname(os.path.abspath(__file__))
PROJ = os.path.dirname(TOOLS)
sys.path.insert(0, TOOLS)
import assets

FDIR = os.path.join(PROJ, "resources", "fonts")

# ---------------------------------------------------------------- fonts
WORD_CHARS = "ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789-° "
word = assets.build_font("SairaSemiCondensed-ExtraBold.ttf", 22, WORD_CHARS)
assets.write_bmfont(word, "word", FDIR, "Context Ahead Pixel word")

TINY_CHARS = "0123456789:%-.+/ABCDEFGHIJKLMNOPQRSTUVWXYZ °~"
tiny = assets.build_font("SairaSemiCondensed-SemiBold.ttf", 10, TINY_CHARS, tracking=1)
g = tiny["glyphs"][" "]
tiny["glyphs"][" "] = (g[0], g[1], g[2], 5)            # a wider word space: "12 MIN AGO" reads as three words
assets.write_bmfont(tiny, "tiny", FDIR, "Context Ahead Pixel tiny")

# ---------------------------------------------------------------- icons (only the ones the face draws)
assets.ICONS["G_BB"] = assets._art(["..##", ".##.", "####", ".##.", "##..", "#..."])
WANTED = ["W_SUN", "W_MOON", "W_PARTLY", "W_CLOUD", "W_RAIN", "W_SNOW", "W_STORM", "W_FOG",
          "I_SUNHZ", "I_HEART", "I_BOLT", "F_MOUNT", "F_BATT", "F_MAIL", "F_BARO", "F_WEEK",
          "N_GUST", "S_STORM", "N_EYE", "N_FREEZE", "N_THERMO", "N_AIR", "N_POLLEN", "N_UV", "N_MOON", "N_RAIN",
          "N_SNOW", "N_UMBRELLA", "N_CLOUD",
          "G_STEPS", "G_FLOORS", "G_INT", "G_MOVE", "G_BB", "G_STRESS", "G_BATT", "G_SOLAR"]
full = assets.ICONS
assets.ICONS = {k: full[k] for k in WANTED}
assets.write_icon_font(FDIR, "icons")
# bar glyph per bar option (Cfg bar order), 255 = none
BAR = ["G_STEPS", "G_FLOORS", "G_INT", "F_WEEK", "G_MOVE", "G_BB", "G_STRESS", "G_BATT", "G_SOLAR", None]
assets.emit_icon_module(os.path.join(PROJ, "source", "Ic.mc"), {"BAR": BAR})
with open(os.path.join(FDIR, "icons.fnt")) as fh:
    t = fh.read()
with open(os.path.join(FDIR, "icons.fnt"), "w", newline="\n") as fh:
    fh.write(t.replace("Instinct Solar Command Icons", "Context Ahead Icons"))

# ---------------------------------------------------------------- settings: one source for phone and watch
SETTINGS = [
    ("Circle", 0, ["Date", "Weather now", "Pressure", "Moon", "Steps", "Intensity today",
                   "Intensity week", "Heart rate", "Body Battery", "Stress", "Altitude", "Battery days",
                   "Solar intensity", "Notifications", "Seconds (wrist raise)", "Off"]),
    ("Bar under the time", 0, ["Steps", "Floors", "Intensity today", "Intensity week", "Move bar", "Body Battery",
                               "Stress", "Battery", "Solar intensity", "Off"]),
    ("Time format", 0, ["Watch setting", "24 hours", "12 hours"]),
    ("Weather update", 4, ["Every 5 min", "Every 10 min", "Every 15 min", "Every 20 min", "Every 30 min",
                           "Every 45 min", "Every 60 min", "Every 90 min", "Every 2 hours"]),
    ("Pollen in Context", 0, ["Off", "On (Europe)"]),
    ("Theme", 0, ["Dark", "Light"]),
    ("Air quality index", 0, ["Auto", "European (EU AQI)", "US (US AQI)"]),
]
assert len(SETTINGS) <= 32
for t_, d, opts in SETTINGS:
    assert 0 <= d < len(opts) and all(o.isascii() and "," not in o for o in opts)
with open(os.path.join(PROJ, "source", "SetText.mc"), "w", newline="\n") as fh:
    fh.write("// Generated by tools/make_project.py: the on-watch settings menu, in the same order as the phone\n")
    fh.write("// settings. Stored values are the option positions. Each setting's texts are one string resource\n")
    fh.write("// (\"Title|Option|...\"), loaded only while the menu shows it, so they cost no memory while the face runs.\n")
    fh.write("import Toybox.Lang;\nimport Toybox.WatchUi;\n\nmodule SetText {\n")
    fh.write("    const DEFAULTS = [" + ", ".join(str(d) for _, d, _ in SETTINGS) + "]b;\n")
    fh.write("    const COUNTS = [" + ", ".join(str(len(o)) for _, _, o in SETTINGS) + "]b;\n")
    fh.write("    const MENUS = [" + ", ".join(f"Rez.Strings.menu{i}" for i in range(len(SETTINGS))) + "];\n\n")
    fh.write("    // field j of setting i's menu string (0 the title, 1.. the options)\n")
    fh.write("    function text(i, j) {\n")
    fh.write("        var s = WatchUi.loadResource(MENUS[i]) as Lang.String;\n")
    fh.write("        for (var k = 0; k < j; k += 1) {\n")
    fh.write("            s = s.substring((s.find(\"|\") as Lang.Number) + 1, s.length()) as Lang.String;\n")
    fh.write("        }\n")
    fh.write("        var e = s.find(\"|\");\n")
    fh.write("        return (e == null) ? s : s.substring(0, e);\n")
    fh.write("    }\n}\n")
sdir = os.path.join(PROJ, "resources", "settings")
os.makedirs(sdir, exist_ok=True)
with open(os.path.join(sdir, "properties.xml"), "w", newline="\n") as fh:
    fh.write("<properties>\n")
    for i, (_, d, _) in enumerate(SETTINGS):
        fh.write(f'    <property id="k{i}" type="number">{d}</property>\n')
    fh.write("</properties>\n")
strings = []
with open(os.path.join(sdir, "settings.xml"), "w", newline="\n") as fh:
    fh.write("<settings>\n")
    for i, (title, _, opts) in enumerate(SETTINGS):
        strings.append((f"st{i}", title))
        fh.write(f'    <setting propertyKey="@Properties.k{i}" title="@Strings.st{i}">\n')
        fh.write('        <settingConfig type="list">\n')
        for j, o in enumerate(opts):
            strings.append((f"so{i}_{j}", o))
            fh.write(f'            <listEntry value="{j}">@Strings.so{i}_{j}</listEntry>\n')
        fh.write("        </settingConfig>\n    </setting>\n")
    fh.write("</settings>\n")
with open(os.path.join(sdir, "strings.xml"), "w", newline="\n") as fh:
    fh.write("<strings>\n")
    for sid, val in strings:
        fh.write(f'    <string id="{sid}" scope="settings">{escape(val)}</string>\n')
    # the watch menu: one string per setting, "Title|Option|Option|...", loaded only while the menu shows it
    for i, (title, _, opts) in enumerate(SETTINGS):
        fh.write(f'    <string id="menu{i}">{escape("|".join([title] + opts))}</string>\n')
    fh.write("</strings>\n")

# ---------------------------------------------------------------- launcher icon: a sun on the horizon, 1-bit
ic = Image.new("1", (40, 40), 0)
d = ImageDraw.Draw(ic)
d.rounded_rectangle((1, 1, 38, 38), radius=8, outline=1, width=2)
d.pieslice((9, 12, 31, 34), 180, 360, fill=1)          # the sun, half above the horizon
d.rectangle((6, 24, 33, 25), fill=1)                   # the horizon
for x0 in (8, 16, 24):                                 # "ahead": three chevrons under the horizon
    d.line((x0, 29, x0 + 3, 32), fill=1); d.line((x0 + 3, 32, x0, 35), fill=1)
    d.line((x0 + 1, 29, x0 + 4, 32), fill=1); d.line((x0 + 4, 32, x0 + 1, 35), fill=1)
for a in range(0, 181, 45):                            # rays
    import math
    r0, r1 = 13, 16
    cx, cy = 20, 23
    x0, y0 = cx + r0 * math.cos(math.radians(180 + a)), cy + r0 * math.sin(math.radians(180 + a))
    x1, y1 = cx + r1 * math.cos(math.radians(180 + a)), cy + r1 * math.sin(math.radians(180 + a))
    d.line((x0, y0, x1, y1), fill=1, width=2)
ic.save(os.path.join(PROJ, "resources", "drawables", "launcher_icon.png"))

import xml.dom.minidom
for root, _, files in os.walk(os.path.join(PROJ, "resources")):
    for f in files:
        if f.endswith(".xml"):
            xml.dom.minidom.parse(os.path.join(root, f))
print("generated: fonts word/tiny/icons, Ic.mc, SetText.mc, settings XML, launcher icon; XML validated")
